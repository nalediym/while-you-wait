#!/usr/bin/env bun
// Generates hooks/games/puzzles.ts from data/crosswords.json.
//   bun scripts/build-puzzles.ts           # write the file
//   bun scripts/build-puzzles.ts --check   # exit 1 if the file is stale

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..");
const SRC = join(ROOT, "data/crosswords.json");
const OUT = join(ROOT, "hooks/games/puzzles.ts");

type Puzzle = {
  id: string;
  title: string;
  grid: string[];
  clues: { across: Record<string, string>; down: Record<string, string> };
};

const data = JSON.parse(readFileSync(SRC, "utf8")) as { version: number; puzzles: Puzzle[] };

const q = (s: string) => JSON.stringify(s);
const rec = (r: Record<string, string>) =>
  `{ ${Object.entries(r)
    .sort(([a], [b]) => Number(a) - Number(b))
    .map(([k, v]) => `${q(k)}: ${q(v)}`)
    .join(", ")} }`;

const body = data.puzzles
  .map(
    (p) => `  {
    id: ${q(p.id)},
    title: ${q(p.title)},
    grid: [${p.grid.map(q).join(", ")}],
    clues: {
      across: ${rec(p.clues.across)},
      down: ${rec(p.clues.down)},
    },
  },`,
  )
  .join("\n");

const out = `// GENERATED by scripts/build-puzzles.ts from data/crosswords.json — do not edit.
export type PuzzleData = { id: string; title: string; grid: readonly string[]; clues: { across: Readonly<Record<string, string>>; down: Readonly<Record<string, string>> } }

export const PUZZLES: readonly PuzzleData[] = [
${body}
]
`;

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== out) {
    console.error("hooks/games/puzzles.ts is stale — run: bun scripts/build-puzzles.ts");
    process.exit(1);
  }
  console.log(`ok: hooks/games/puzzles.ts is up to date (${data.puzzles.length} puzzles)`);
} else {
  writeFileSync(OUT, out);
  console.log(`wrote hooks/games/puzzles.ts (${data.puzzles.length} puzzles)`);
}
