/** Horizontal runs of set bits, as one SVG path in glyph units. */
const glyphPath = (rows: number[], width: number): string => {
  let d = ''
  rows.forEach((bits, y) => {
    let x = 0
    while (x < width) {
      if (!((bits >> (width - 1 - x)) & 1)) {
        x++
        continue
      }
      let n = 0
      while (x + n < width && (bits >> (width - 1 - x - n)) & 1) n++
      d += `M${x} ${y}h${n}v1h-${n}z`
      x += n
    }
  })
  return d
}

export const normalize = (s: string): string => s.toUpperCase().replace(/[’‘]/g, "'").replace(/[“”]/g, '"')

const idOf = (font: 'a' | 'd', ch: string) => `${font}${ch.codePointAt(0)!.toString(16)}`

/**
 * Collects the glyphs a drawing uses, so each is defined once in <defs> and
 * placed with <use>: keeps a text-heavy screen well under the Svg size cap.
 */
export class Typesetter {
  private used = new Map<string, string>()

  /** 5x7 text at (x, y) top-left, 6px advance per char (× scale). */
  text(s: string, x: number, y: number, fill: string, scale = 1): string {
    let out = ''
    let cx = x
    for (const ch of normalize(s)) {
      const rows = FONT5x7[ch] ?? FONT5x7['?']!
      if (ch !== ' ') {
        const id = idOf('a', ch)
        if (!this.used.has(id)) this.used.set(id, glyphPath(rows, 5))
        out += scale === 1 ? `<use href="#${id}" x="${cx}" y="${y}" fill="${fill}"/>` : `<use href="#${id}" transform="translate(${cx} ${y}) scale(${scale})" fill="${fill}"/>`
      }
      cx += 6 * scale
    }
    return out
  }

  /** 3x5 digits, 4px advance. */
  digits(s: string, x: number, y: number, fill: string): string {
    let out = ''
    let cx = x
    for (const ch of s) {
      const rows = DIGITS3x5[ch]
      if (rows) {
        const id = idOf('d', ch)
        if (!this.used.has(id)) this.used.set(id, glyphPath(rows, 3))
        out += `<use href="#${id}" x="${cx}" y="${y}" fill="${fill}"/>`
      }
      cx += 4
    }
    return out
  }

  defs(): string {
    return [...this.used].map(([id, d]) => `<path id="${id}" d="${d}"/>`).join('')
  }
}

export const textWidth = (s: string, scale = 1): number => normalize(s).length * 6 * scale - scale

/** Word-wraps to `cols` characters per line. */
export const wrap = (s: string, cols: number): string[] => {
  const lines: string[] = []
  let line = ''
  for (const word of normalize(s).split(/\s+/).filter(Boolean)) {
    if (line && (line + ' ' + word).length > cols) {
      lines.push(line)
      line = word
    } else line = line ? `${line} ${word}` : word
    while (line.length > cols) {
      lines.push(line.slice(0, cols))
      line = line.slice(cols)
    }
  }
  if (line) lines.push(line)
  return lines
}
